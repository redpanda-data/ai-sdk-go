// TestDecisionsHold fails when the catalogue the code builds contradicts a
// recorded review decision (RULES.md, Principles). It checks the snapshot
// encoded from the code, not the committed file.
func TestDecisionsHold(t *testing.T) {
	t.Parallel()

	file, err := os.ReadFile(filepath.Join("..", "..", ".github", "reconcile-models", "decisions.yaml"))
	require.NoError(t, err)

	raw, err := os.ReadFile(filepath.Join("..", "..", reconcile.RulesPath))
	require.NoError(t, err)

	rules, _ := reconcile.ParseRules(raw)

	var generated bytes.Buffer
	require.NoError(t, snapshot.Encode(&generated, allCatalogs()...))

	assert.Empty(t, checkDecisions(file, generated.Bytes(), rules.Questions),
		"the catalogue contradicts a recorded decision: change the code back, or update the decision in the same PR")
}

// TestDecisionFieldsMatchRules keeps lockedKeys equal to RULES.md's Field
// table, which TestRulesFile holds equal to the report's fields.
func TestDecisionFieldsMatchRules(t *testing.T) {
	t.Parallel()

	raw, err := os.ReadFile(filepath.Join("..", "..", reconcile.RulesPath))
	require.NoError(t, err)

	rules, _ := reconcile.ParseRules(raw)
	assert.ElementsMatch(t, slices.Collect(maps.Keys(rules.Fields)), slices.Collect(maps.Keys(lockedKeys)))
}

func TestCheckDecisions(t *testing.T) {
	t.Parallel()

	const fable = `{"facts": {"anthropic/claude-fable-5": {"released": "2026-05-01"}},
		"providers": [{"provider": "aws.bedrock", "offerings": [{
			"id": "eu.anthropic.claude-fable-5", "model": "anthropic/claude-fable-5",
			"capabilities": {"tools": true},
			"constraints": {"max_input_tokens": 1000000, "max_output_tokens": 128000, "supported_params": ["max_tokens"]},
			"lifecycle": {"stage": "ga"},
			"pricing": {"default": {"base": {"input_microcents_per_million": 1100000000}}}}]}]}`

	item := func(id, field, kind string, extra ...string) string {
		lines := append([]string{
			"id: " + id, "offering: bedrock:eu.anthropic.claude-fable-5", "field: " + field,
			"kind: " + kind, `reason: "Agreed in review."`, "decided: 2026-10-13", "review_by: 2027-01-13",
		}, extra...)

		return "  - " + strings.Join(lines, "\n    ") + "\n"
	}
	keep := func(field, lock string) string { return item("DEC-001", field, reconcile.KindKeep, "lock: "+lock) }
	keepGA := keep("lifecycle", `{"stage": "ga"}`)
	hold := item("DEC-002", reconcile.FieldNewModel, reconcile.KindHold)
	holdCopy := item("DEC-002", reconcile.FieldNewCopy, reconcile.KindHold)
	gap := item("DEC-002", "capability", reconcile.KindHold, "rule: reasoning-unsendable")
	keyed := func(keys, lock string) string {
		return item("DEC-001", "capability", reconcile.KindKeep, "keys: "+keys, "lock: "+lock)
	}
	asks := map[string]string{
		"reasoning-unsendable": "Add support, or leave them out?", "out-of-reach": "Make it by hand?",
		reconcile.JudgmentRule: "Add a rule?",
	}
	reviewBy := func(date string) string { return strings.Replace(keepGA, "2027-01-13", date, 1) }

	tests := []struct {
		name        string
		decisions   string
		snapshot    string
		wantProblem string
	}{
		{"lifecycle lock holds", keepGA, fable, ""},
		{"price lock holds", keep("price", `{"default": {"base": {"input_microcents_per_million": 1100000000}}}`), fable, ""},
		{"limit lock leaves other constraints out", keep("limit", `{"max_input_tokens": 1000000, "max_output_tokens": 128000}`), fable, ""},
		{"capability lock holds", keep("capability", `{"capabilities": {"tools": true}}`), fable, ""},
		{"release date lock holds", keep("release_date", `"2026-05-01"`), fable, ""},
		{"kept model present", item("DEC-003", reconcile.FieldNewModel, reconcile.KindKeep), fable, ""},
		{"kept copy present", item("DEC-003", reconcile.FieldNewCopy, reconcile.KindKeep), fable, ""},
		{"held offering absent", hold, `{}`, ""},
		{"held copy absent", holdCopy, `{}`, ""},
		{"kept offering removed", keepGA, `{}`, "DEC-001 keep bedrock:eu.anthropic.claude-fable-5 lifecycle: the offering is missing"},
		{"locked value moved", keep("lifecycle", `{"stage": "deprecated"}`), fable, `DEC-001 keep bedrock:eu.anthropic.claude-fable-5 lifecycle: got {"stage":"ga"}`},
		{"held offering added", hold, fable, "DEC-002 hold bedrock:eu.anthropic.claude-fable-5 new_model: the offering is in the catalogue"},
		{"held copy added", holdCopy, fable, "DEC-002 hold bedrock:eu.anthropic.claude-fable-5 new_copy: the offering is in the catalogue"},
		{"unknown key", keepGA + "    colour: red\n", fable, "decisions.yaml"},
		{"duplicate ID", keepGA + keepGA, fable, "DEC-001: duplicate ID"},
		{"two decisions on one field", keepGA + item("DEC-004", "lifecycle", reconcile.KindKeep, `lock: {"stage": "ga"}`), fable, "DEC-004: DEC-001 already covers"},
		{"two rules share a field", gap + item("DEC-004", "capability", reconcile.KindHold, "rule: out-of-reach"), fable, ""},
		{"one rule twice on a field", gap + item("DEC-004", "capability", reconcile.KindHold, "rule: reasoning-unsendable"), fable, "DEC-004: DEC-002 already covers"},
		{"no rule beside a rule", gap + keyed(`[capabilities.tools]`, `{"tools": true}`), fable, "DEC-001: DEC-002 already covers"},
		{"a rule beside no rule", keyed(`[capabilities.tools]`, `{"tools": true}`) + gap, fable, "DEC-002: DEC-001 already covers"},
		{"keep without a lock", keep("lifecycle", "null"), fable, "a keep needs a lock"},
		{"lock on new_model", item("DEC-003", reconcile.FieldNewModel, reconcile.KindKeep, `lock: {"stage": "ga"}`), fable, "new_model takes no lock"},
		{"lock on new_copy", item("DEC-003", reconcile.FieldNewCopy, reconcile.KindKeep, `lock: {"stage": "ga"}`), fable, "new_copy takes no lock"},
		{"hold on a field answers its rule", gap, fable, ""},
		{"hold on a field needs its rule", item("DEC-002", "price", reconcile.KindHold), fable, "DEC-002: a hold on price names the rule whose question it answers"},
		{"hold on a field needs the offering", gap, `{}`, "DEC-002 hold bedrock:eu.anthropic.claude-fable-5 capability: the offering is missing"},
		{"hold on a field takes no lock", gap + `    lock: {"capabilities": {"tools": true}}` + "\n", fable, "DEC-002: a hold takes no lock"},
		{"rule that asks no question", strings.Replace(gap, "reasoning-unsendable", "price-follow", 1), fable, "DEC-002: rule price-follow asks no question"},
		{"hold naming no-rule", strings.Replace(gap, "reasoning-unsendable", reconcile.JudgmentRule, 1), fable, "DEC-002: a hold can't name no-rule"},
		{"rule on a held model", hold + "    rule: out-of-reach\n", `{}`, "DEC-002: new_model takes no rule"},
		{"rule on a kept copy", item("DEC-003", reconcile.FieldNewCopy, reconcile.KindKeep, "rule: out-of-reach"), fable, "DEC-003: new_copy takes no rule"},
		{"keep that answers one rule", keepGA + "    rule: out-of-reach\n", fable, ""},
		{"keys lock only their part", keyed(`[capabilities.tools]`, `{"tools": true}`), fable, ""},
		{"a missing part locks as empty", keyed(`[reasoning]`, `{}`), fable, ""},
		{"a locked part moved", keyed(`[capabilities.tools]`, `{"tools": false}`), fable, `DEC-001 keep bedrock:eu.anthropic.claude-fable-5 capability: got {"tools":true}`},
		{"keys that lock one name", keyed(`[capabilities.reasoning, reasoning]`, `{}`), fable, "DEC-001: keys capabilities.reasoning and reasoning would both lock reasoning"},
		{"a key outside its field", keyed(`[pricing]`, `{}`), fable, "DEC-001: key pricing isn't part of capability"},
		{"a key too deep", keyed(`[capabilities.tools.x]`, `{}`), fable, "DEC-001: key capabilities.tools.x isn't part of capability"},
		{"keys on a hold", gap + "    keys: [reasoning]\n", fable, "DEC-002: only a keep on a value names keys"},
		{"keep on location", keep("location", `["global"]`), fable, "DEC-001: location takes no decision yet: served locations are not in the snapshot"},
		{"hold on location", item("DEC-002", "location", reconcile.KindHold), `{}`, "DEC-002: location takes no decision yet: served locations are not in the snapshot"},
		{"unknown package", strings.Replace(keepGA, "bedrock:", "azure:", 1), fable, "unknown package azure"},
		{"bad date", reviewBy("soon"), fable, "review_by"},
		{"review a year out", reviewBy("2027-10-13"), fable, ""},
		{"review more than a year out", reviewBy("2027-10-14"), fable, "DEC-001: review_by is after decided, and at most a year after it"},
		{"review before decided", reviewBy("2026-10-01"), fable, "DEC-001: review_by is after decided, and at most a year after it"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			problems := checkDecisions([]byte("decisions:\n"+tt.decisions), []byte(tt.snapshot), asks)
			if tt.wantProblem == "" {
				assert.Empty(t, problems)
				return
			}

			assert.Contains(t, strings.Join(problems, "\n"), tt.wantProblem)
		})
	}
}
