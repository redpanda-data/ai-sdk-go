// TestDecisionsHold fails when the catalogue the code builds contradicts a
// recorded review decision (RULES.md section D). It checks the snapshot
// encoded from the code, not the committed file.
func TestDecisionsHold(t *testing.T) {
	t.Parallel()

	file, err := os.ReadFile(filepath.Join("..", "..", ".github", "reconcile-models", "decisions.yaml"))
	require.NoError(t, err)

	var generated bytes.Buffer
	require.NoError(t, snapshot.Encode(&generated, allCatalogs()...))

	assert.Empty(t, checkDecisions(file, generated.Bytes()),
		"the catalogue contradicts a recorded decision: change the code back, or update the decision in the same PR")
}

// TestDecisionFieldsMatchRules keeps lockedKeys equal to RULES.md's Field
// table, which TestRulesFile holds equal to the report's fields.
func TestDecisionFieldsMatchRules(t *testing.T) {
	t.Parallel()

	raw, err := os.ReadFile(filepath.Join("..", "..", reconcile.RulesPath))
	require.NoError(t, err)

	rules, _ := reconcile.ParseRules(raw)
	assert.ElementsMatch(t, slices.Collect(maps.Keys(rules.Fields)), slices.Collect(maps.Keys(lockedKeys)))
}

func TestCheckDecisions(t *testing.T) {
	t.Parallel()

	const fable = `{"facts": {"anthropic/claude-fable-5": {"released": "2026-05-01"}},
		"providers": [{"provider": "aws.bedrock", "offerings": [{
			"id": "eu.anthropic.claude-fable-5", "model": "anthropic/claude-fable-5",
			"capabilities": {"tools": true},
			"constraints": {"max_input_tokens": 1000000, "max_output_tokens": 128000, "supported_params": ["max_tokens"]},
			"lifecycle": {"stage": "ga"},
			"pricing": {"default": {"base": {"input_microcents_per_million": 1100000000}}}}]}]}`

	item := func(id, field, kind string, extra ...string) string {
		lines := append([]string{
			"id: " + id, "offering: bedrock:eu.anthropic.claude-fable-5", "field: " + field,
			"kind: " + kind, `reason: "Agreed in review."`, "decided: 2026-10-13", "review_by: 2027-01-13",
		}, extra...)

		return "  - " + strings.Join(lines, "\n    ") + "\n"
	}
	keep := func(field, lock string) string { return item("DEC-001", field, reconcile.KindKeep, "lock: "+lock) }
	keepGA := keep("lifecycle", `{"stage": "ga"}`)
	hold := item("DEC-002", reconcile.FieldNewModel, reconcile.KindHold)

	tests := []struct {
		name        string
		decisions   string
		snapshot    string
		wantProblem string
	}{
		{"lifecycle lock holds", keepGA, fable, ""},
		{"price lock holds", keep("price", `{"default": {"base": {"input_microcents_per_million": 1100000000}}}`), fable, ""},
		{"limit lock leaves other constraints out", keep("limit", `{"max_input_tokens": 1000000, "max_output_tokens": 128000}`), fable, ""},
		{"capability lock holds", keep("capability", `{"capabilities": {"tools": true}}`), fable, ""},
		{"release date lock holds", keep("release_date", `"2026-05-01"`), fable, ""},
		{"kept model present", item("DEC-003", reconcile.FieldNewModel, reconcile.KindKeep), fable, ""},
		{"held offering absent", hold, `{}`, ""},
		{"kept offering removed", keepGA, `{}`, "DEC-001 keep bedrock:eu.anthropic.claude-fable-5 lifecycle: the offering is missing"},
		{"locked value moved", keep("lifecycle", `{"stage": "deprecated"}`), fable, `DEC-001 keep bedrock:eu.anthropic.claude-fable-5 lifecycle: got {"stage":"ga"}`},
		{"held offering added", hold, fable, "DEC-002 hold bedrock:eu.anthropic.claude-fable-5 new_model: the offering is in the catalogue"},
		{"unknown key", keepGA + "    colour: red\n", fable, "decisions.yaml"},
		{"duplicate ID", keepGA + keepGA, fable, "DEC-001: duplicate ID"},
		{"two decisions on one field", keepGA + item("DEC-004", "lifecycle", reconcile.KindKeep, `lock: {"stage": "ga"}`), fable, "DEC-004: DEC-001 already covers"},
		{"keep without a lock", keep("lifecycle", "null"), fable, "a keep needs a lock"},
		{"lock on new_model", item("DEC-003", reconcile.FieldNewModel, reconcile.KindKeep, `lock: {"stage": "ga"}`), fable, "new_model takes no lock"},
		{"hold on another field", item("DEC-002", "price", reconcile.KindHold), fable, "a hold applies only to new_model"},
		{"unknown package", strings.Replace(keepGA, "bedrock:", "azure:", 1), fable, "unknown package azure"},
		{"bad date", strings.Replace(keepGA, "2027-01-13", "soon", 1), fable, "review_by"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			problems := checkDecisions([]byte("decisions:\n"+tt.decisions), []byte(tt.snapshot))
			if tt.wantProblem == "" {
				assert.Empty(t, problems)
				return
			}

			assert.Contains(t, strings.Join(problems, "\n"), tt.wantProblem)
		})
	}
}
